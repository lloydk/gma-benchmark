// Emit hot intersection bodies without maintaining duplicate equations.
// Fits and hue caches are unchanged; the cache is still populated at runtime.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";

const check = process.argv.includes("--check");
assert(process.argv.slice(2).every(arg => arg === "--check"));
const read = path => readFileSync(new URL(path, import.meta.url), "utf8");
const replaceOnce = (text, from, to) => {
	assert.equal(text.split(from).length, 2, `expected exactly one ${from}`);
	return text.replace(from, () => to);
};
let source = read("./templates/bottosson-mapper.js");
const intersection = read("./templates/bottosson-intersection.js").trimEnd();
const parameters = ["q0", "q1", "q2", "l1", "c1", "l0", "cuspL", "cuspC"];
const argumentsByMode = {
	cached: ["q0", "q1", "q2", "L", "C", "L0", "cuspL", "cuspC"],
	uncached: ["unitA * KA0 + unitB * KB0", "unitA * KA1 + unitB * KB1", "unitA * KA2 + unitB * KB2", "L", "C", "L0", "cusp[0]", "cusp[1]"],
};
for (const [mode, args] of Object.entries(argumentsByMode)) {
	const bindings = parameters.map((name, i) => `const arg_${name} = ${args[i]};`).join("\n");
	const body = `${bindings}\n\n${intersection}`.split("\n").map(line => line ? `\t\t\t${line}` : "").join("\n");
	source = replaceOnce(source, `/* @intersection:${mode} */`, `let t;\n\t\t{\n${body}\n\t\t}`);
}

// Use the canonical conversion's exact arithmetic and membership predicate.
// Only control flow and the local transfer-function name change. The template
// computes a/b from the authored input and retains the direction on rejection.
const conversion = read("../src/rgb-convert.js");
const begin = "\t\t// @bottosson-precheck-begin\n";
const end = "\n\t\t// @bottosson-precheck-end";
assert.equal(conversion.split(begin).length, 2);
assert.equal(conversion.split(end).length, 2);
let precheck = conversion.split(begin)[1].split(end)[0];
precheck = replaceOnce(precheck, "return false;", "break precheck;");
precheck = replaceOnce(precheck, "return true;", "return out;");
assert.equal(precheck.split("encodeClamped(").length, 4);
precheck = precheck.replaceAll("encodeClamped(", "clampedGamma(");
precheck = precheck.split("\n").map(line => `\t\t${line}`).join("\n").trimStart();
source = replaceOnce(source, "/* @canonical-precheck */", precheck);
assert(!source.includes("/* @"), "unexpanded template slot");
source = "// Generated by scripts/generate-bottosson-kernel.mjs; do not edit.\n"
	+ "// Edit scripts/templates/bottosson-*.js and src/rgb-convert.js, then regenerate.\n"
	+ source;
const output = new URL("../src/bottosson-factory.js", import.meta.url);
if (check) assert.equal(readFileSync(output, "utf8"), source, "stale Bottosson kernel; run node scripts/generate-bottosson-kernel.mjs");
else writeFileSync(output, source);
console.log(`Bottosson kernel ${check ? "is current" : "generated"}`);
