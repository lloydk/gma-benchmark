// Development-time bridge only; shipped JavaScript has no Rust dependency.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { loadProfiles } from "./rgb-gamut-profiles.mjs";

const source = await loadProfiles();
const profiles = source.map(({ name, encoding, rgbToXyz, xyzToRgb, lmsToRgb, rgbToLms, oklabToLms }) => ({
	id: name, encoding, rgbToXyz, xyzToRgb, lmsToRgb, rgbToLms, oklabToLms,
}));
const content = `// Generated by scripts/generate-rgb-spaces.mjs; do not edit.\n// Physical D65 spaces and composed conversion matrices from the Rust profiles.\n// P3 preserves the incumbent coefficients and arithmetic convention.\nexport const profiles = ${JSON.stringify(profiles, null, "\t")};\n`;
const file = new URL("../src/generated/rgb-spaces.js", import.meta.url);
if (process.argv.includes("--check")) assert.equal(readFileSync(file, "utf8"), content, "RGB space data is stale");
else writeFileSync(file, content);
console.log(`${process.argv.includes("--check") ? "Checked" : "Generated"} three RGB spaces`);

// Keep numerical policy in a separate generated artifact, never in descriptors.
const windows = Object.fromEntries(source.map(({ name, blueFoldWindow }) => [name, blueFoldWindow]));
assert.ok(Object.values(windows).every(v => v === null || (v?.length === 2 && v.every(Number.isFinite))));
const policyFile = new URL("../src/generated/matrix-solver-policy.js", import.meta.url);
const policy = `// Generated by scripts/generate-rgb-spaces.mjs from Rust blue_fold_window.\nexport const blueFoldWindows = Object.freeze(Object.fromEntries(Object.entries(${JSON.stringify(windows, null, "\t")}).map(([id, window]) => [id, window && Object.freeze(window)])));\n`;
if (process.argv.includes("--check")) assert.equal(readFileSync(policyFile, "utf8"), policy, "Matrix solver policy is stale");
else writeFileSync(policyFile, policy);
