function rustData(profile, primaryContent, lines, fits, note) {
    const array = values => `[${values.map(v => Number.isInteger(v) ? `${v}.0` : String(v)).join(", ")}]`;
    return `// Generated by scripts/generate-bottosson.mjs; do not edit.\n`
        + `// ${profile.name}: ${note}\n`
        + `// Five-term seed plus one Halley step; not an exact boundary solver.\n`
        + primaryContent
        + `pub const RED_SECTOR: [Float; 2] = ${array(lines[0])};\n`
        + `pub const GREEN_SECTOR: [Float; 2] = ${array(lines[1])};\n`
        + `pub const SATURATION_FITS: [[Float; 5]; 3] = [\n${fits.map(k => `    ${array(k)},\n`).join("")}];\n`;
}

const check = process.argv.includes("--check");
assert(process.argv.slice(2).every(arg => arg === "--check"));
const profiles = await loadProfiles();
const dot = (a, b) => a.reduce((sum, x, i) => sum + x * b[i], 0);
const basis = (a, b) => [1, a, b, a * a, a * b];

// Isolate crossings between stationary points, then bisect. The fitted
// saturation range is [0,4]; assert every sample has a positive crossing.
function roots([a, b, c, d]) {
    const evaluate = x => ((a * x + b) * x + c) * x + d;
    const discriminant = b * b - 3 * a * c;
    let points = [0, 4];
    if (discriminant >= 0) {
        const q = -b - Math.sign(b) * Math.sqrt(discriminant);
        points.push(q / (3 * a), c / q);
    }
    points = points.filter(x => Number.isFinite(x) && x >= 0 && x <= 4)
        .sort((a, b) => a - b);
    const result = [];
    for (let i = 1; i < points.length; i++) {
        let lo = points[i - 1], hi = points[i];
        const sign = evaluate(lo) >= 0;
        if ((evaluate(hi) >= 0) === sign) continue;
        for (let j = 0; j < 60; j++) {
            const mid = (lo + hi) / 2;
            if ((evaluate(mid) >= 0) === sign) lo = mid;
            else hi = mid;
        }
        result.push((lo + hi) / 2);
    }
    return result;
}

// Small dense systems only (sector half-planes and five fit coefficients).
function solve(matrix, rhs) {
    const a = matrix.map((row, i) => [...row, rhs[i]]);
    const n = rhs.length;
    for (let i = 0; i < n; i++) {
        let pivotRow = i;
        for (let j = i + 1; j < n; j++) {
            if (Math.abs(a[j][i]) > Math.abs(a[pivotRow][i])) pivotRow = j;
        }
        [a[i], a[pivotRow]] = [a[pivotRow], a[i]];
        const pivot = a[i][i];
        assert(Number.isFinite(pivot) && Math.abs(pivot) >= 1e-30, "Singular fit system");
        for (let j = i; j <= n; j++) a[i][j] /= pivot;
        for (let j = 0; j < n; j++) {
            if (j === i) continue;
            const factor = a[j][i];
            for (let k = i; k <= n; k++) a[j][k] -= factor * a[i][k];
        }
    }
    return a.map(row => row[n]);
}

function halley(s, [a, b, c, d]) {
    const f = ((a * s + b) * s + c) * s + d;
    const f1 = (3 * a * s + 2 * b) * s + c;
    const f2 = 6 * a * s + 2 * b;
    return s - f * f1 / (f1 * f1 - 0.5 * f * f2);
}

function fit(data) {
    const normal = Array.from({ length: 5 }, () => Array(5).fill(0));
    const rhs = Array(5).fill(0);
    for (const { v, s } of data) {
        for (let i = 0; i < 5; i++) {
            rhs[i] += v[i] * s;
            for (let j = 0; j < 5; j++) normal[i][j] += v[i] * v[j];
        }
    }
    let coefficients = solve(normal, rhs);
    let best = [...coefficients], bestMax = Infinity;
    let damping = 1e-5;
    // Refine the post-Halley error, rather than the raw seed error. Damped
    // Gauss-Newton with iteratively reweighted residuals emphasizes the worst
    // samples. Keep the lowest measured maximum, not simply the last iterate.
    for (let iteration = 0; iteration < 100; iteration++) {
        const errors = data.map(d => halley(dot(coefficients, d.v), d.p) - d.s);
        const maximum = Math.max(...errors.map(Math.abs));
        if (maximum < bestMax) {
            bestMax = maximum;
            best = [...coefficients];
        }
        if (maximum === 0) break;
        const weights = errors.map(e => Math.max(0.001, (e / maximum) ** 2));
        const oldLoss = errors.reduce((sum, e, i) => sum + e * e * weights[i], 0);
        const normal = Array.from({ length: 5 }, () => Array(5).fill(0));
        const rhs = Array(5).fill(0);
        for (let t = 0; t < data.length; t++) {
            const d = data[t], seed = dot(coefficients, d.v), epsilon = 1e-5;
            const derivative = (halley(seed + epsilon, d.p) - halley(seed - epsilon, d.p)) / (2 * epsilon);
            const jacobian = d.v.map(x => x * derivative), weight = weights[t];
            for (let i = 0; i < 5; i++) {
                rhs[i] -= weight * jacobian[i] * errors[t];
                for (let j = 0; j < 5; j++) normal[i][j] += weight * jacobian[i] * jacobian[j];
            }
        }
        for (let i = 0; i < 5; i++) normal[i][i] += damping * Math.max(normal[i][i], 1e-8);
        const step = solve(normal, rhs);
        const trial = coefficients.map((v, i) => v + step[i]);
        const loss = data.reduce((sum, d, i) => sum + weights[i] * (halley(dot(trial, d.v), d.p) - d.s) ** 2, 0);
        if (loss < oldLoss) {
            coefficients = trial;
            damping = Math.max(1e-12, damping / 3);
        } else {
            damping = Math.min(1e12, damping * 10);
        }
    }
    return { k: best, max: bestMax };
}

function sample(profile, channel, h) {
    const a = Math.cos(h), b = Math.sin(h);
    const q = profile.oklabToLms.map(r => r[1] * a + r[2] * b);
    const row = profile.lmsToRgb[channel];
    const p = [
        dot(row, q.map(x => x * x * x)),
        3 * dot(row, q.map(x => x * x)),
        3 * dot(row, q),
        dot(row, [1, 1, 1]),
    ];
    const s = roots(p)[0];
    assert(s > 0 && Number.isFinite(s), `No lower-face crossing at ${profile.name}, ${channel}, ${h}`);
    return { s, p, v: basis(a, b) };
}
for (const profile of profiles) {
    // Exact primary hues determine the two sector half-planes. Solve their
    // intersection with the unit circle; no hand-maintained sector constants.
    const hues = [0, 1, 2].map(j => {
        const [l, m, s] = profile.rgbToLms.map(r => Math.cbrt(r[j]));
        const a = 1.9779985324311684 * l - 2.4285922420485799 * m + 0.4505937096174110 * s;
        const b = 0.0259040424655478 * l + 0.7827717124575296 * m - 0.8086757549230774 * s;
        return (Math.atan2(b, a) + 2 * Math.PI) % (2 * Math.PI);
    });
    const primaryContent = `pub const PRIMARY_HUES: [f64; 3] = [${hues.map(h => h * 180 / Math.PI).join(", ")}];\n`;
    if (profile.name === "display-p3") {
        const file = new URL("../rust/src/generated/bottosson_display_p3.rs", import.meta.url);
        const content = rustData(profile, primaryContent, [p3Fit.red,p3Fit.green], p3Fit.fits, "pinned incumbent fits; regenerated primary hues.");
        if (check) assert(readFileSync(file, "utf8") === content, "P3 fit data is stale");
        else writeFileSync(file, content);
        continue;
    }
    const sectors = [[hues[1], hues[2]], [hues[2], hues[0] + 2 * Math.PI], [hues[0], hues[1]]];
    const lines = [], fits = [], errors = [];
    for (let channel = 0; channel < 3; channel++) {
        const [lo, hi] = sectors[channel];
        lines.push(solve([[Math.cos(lo), Math.sin(lo)], [Math.cos(hi), Math.sin(hi)]], [1, 1]));
        const data = Array.from({ length: 4096 }, (_, i) => sample(profile, channel, lo + (hi - lo) * (i + 0.5) / 4096));
        const result = fit(data);
        fits.push(result.k);
        let maxError = 0;
        // Held-out denser points plus one-sided sector endpoints. Production
        // tests independently assess native f32/f64 conversion and mapping.
        const hs = Array.from({ length: 65536 }, (_, i) => lo + (hi - lo) * (i + 0.25) / 65536);
        for (const delta of [1e-4, 1e-6, 1e-8, 1e-10]) hs.push(lo + delta, hi - delta);
        for (const h of hs) {
            const d = sample(profile, channel, h);
            const seed = dot(result.k, d.v), actual = halley(seed, d.p);
            assert(seed > 0 && actual > 0 && Number.isFinite(actual));
            maxError = Math.max(maxError, Math.abs(actual - d.s));
        }
        assert(maxError < 0.001, `${profile.name} face ${channel}: ${maxError}`);
        errors.push(maxError);
    }
    const content = rustData(profile,primaryContent,lines,fits,"primary-hue sectors; 4096 fit samples per face.");
    const file = new URL(`../rust/src/generated/bottosson_${profile.name}.rs`, import.meta.url);
    if (check) assert(readFileSync(file, "utf8") === content, `${file.pathname} is stale`);
    else writeFileSync(file, content);
    console.log(`${check ? "Checked" : "Generated"} ${profile.name}: held-out saturation errors ${errors.join(", ")}`);
}
