// Run from any directory: node scripts/generate-edge-seeker.mjs [--check]
// Generation uses binary64 JS math; Rust rounds literals into each native lane.
import assert from "node:assert/strict";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { loadProfiles } from "./rgb-gamut-profiles.mjs";
import { makeLut } from "../src/edge-seeker/makeLut.js";

const check = process.argv.slice(2).includes("--check");
assert(process.argv.slice(2).every(arg => arg === "--check"), "usage: generate-edge-seeker.mjs [--check]");
const profiles = await loadProfiles();
const destination = new URL("../rust/src/generated/", import.meta.url);
if (!check) mkdirSync(destination, { recursive: true });
const jsTables = {};

for (const profile of profiles) {
	const decode = profile.encoding === "srgb"
		? x => x <= 0.04045 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4
		: x => x ** 2.4;
	assert(["srgb", "gamma-2.4"].includes(profile.encoding));
	const toLab = (r, g, b) => {
		const [l, m, s] = profile.rgbToLms.map(row => Math.cbrt(row[0] * r + row[1] * g + row[2] * b));
		return [
			0.2104542683093140 * l + 0.7936177747023054 * m - 0.0040720430116193 * s,
			1.9779985324311684 * l - 2.4285922420485799 * m + 0.4505937096174110 * s,
			0.0259040424655478 * l + 0.7827717124575296 * m - 0.8086757549230774 * s,
		];
	};
	// Fail on an incompatible encoding or Oklab kernel instead of silently
	// generating tables that describe a different space from the Rust mapper.
	profile.linearSamples.forEach((x, i) => {
		assert(Math.abs(decode(profile.encodedSamples[i]) - x) < 2e-14);
		toLab(x, 0.25, 0.75).forEach((v, j) => assert(Math.abs(v - profile.labSamples[i][j]) < 2e-14));
	});
	const rows = makeLut((r, g, b) => {
		const [l, a, bb] = toLab(decode(r), decode(g), decode(b));
		let h = Math.atan2(bb, a) * 180 / Math.PI;
		if (h < 0) h += 360;
		return { l, c: Math.sqrt(a * a + bb * bb), h };
	}, 400).map(({ l, c, h, curvature }) => [l, c, h, curvature]);
	assert.equal(rows[0][2], 0);
	assert.equal(rows.at(-1)[2], 360);
	assert.deepEqual(rows[0].filter((_, i) => i !== 2), rows.at(-1).filter((_, i) => i !== 2));
	rows.forEach((row, i) => {
		assert(row.every(Number.isFinite));
		assert(row[0] > 0 && row[0] < 1 && row[1] > 0 && Math.abs(row[3]) < 1);
		if (i) {
			assert(row[2] > rows[i - 1][2]);
			assert(Math.fround(row[2]) > Math.fround(rows[i - 1][2]), "f32 hue knots must remain distinct");
		}
	});
	const literal = x => Number.isInteger(x) ? `${x}.0` : String(x);
	jsTables[profile.name] = rows;
	// Fold repair can leave a large color change across a 0.0001-degree
	// interval (only 3-4 binary32 ULPs). Retain the lost hue bits for that
	// interval and its neighbours; ordinary lookup tables stay unchanged.
	const sharp = rows.flatMap((row, i) => i && row[2] - rows[i - 1][2] < 0.001
		&& Math.abs(row[1] - rows[i - 1][1]) > 0.001 ? [i - 1] : []);
	const conditioning = sharp.map(i => {
		assert(i > 0 && i + 2 < rows.length);
		return `    (${i}, [\n` + rows.slice(i - 1, i + 3).map((row, j) =>
			`        (${literal(row[2])}_f64 - LUT[${i - 1 + j}][2] as f64) as Float,\n`).join("") + `    ], [(LUT[${i - 1}][2] + LUT[${i}][2]) * 0.5, (LUT[${i + 1}][2] + LUT[${i + 2}][2]) * 0.5]),\n`;
	}).join("");
	const content = `// Generated by scripts/generate-edge-seeker.mjs; do not edit.\n`
		+ `// ${profile.name}, ${profile.encoding} encoding, makeLut with 400 slices.\n`
		+ `// [L, C, hue in degrees, curvature]; Float is native f64 or f32.\n`
		+ `pub const LUT: [[Float; 4]; ${rows.length}] = [\n`
		+ rows.map(row => `    [\n${row.map(x => `        ${literal(x)},\n`).join("")}    ],\n`).join("")
		+ "];\n"
		+ `// Compile-time rounding residuals; no f64 arithmetic in f32 kernels.\n`
		+ `pub const SHARP_INTERVALS: [(usize, [Float; 4], [Float; 2]); ${sharp.length}] = [\n${conditioning}];\n`;
	const file = new URL(`edge_seeker_${profile.name.replaceAll("-", "_")}.rs`, destination);
	if (check) assert(readFileSync(file, "utf8") === content, `${file.pathname} is stale; regenerate with the recorded Node version`);
	else writeFileSync(file, content);
	console.log(`${check ? "Checked" : "Generated"} ${profile.name}: ${rows.length} rows, curvature [${Math.min(...rows.map(r => r[3]))}, ${Math.max(...rows.map(r => r[3]))}]`);
}
const jsFile = new URL("../tests/fixtures/edge-seeker.js", import.meta.url);
const jsContent = `// Generated by scripts/generate-edge-seeker.mjs; do not edit.\n// Test fixture only; production JS builds its tables at runtime.\n// Same binary64 rows as Rust: [L, C, hue, curvature], 400 slices.\nconst tables = ${JSON.stringify(jsTables, null, "\t")};\nfor (const rows of Object.values(tables)) { rows.forEach(Object.freeze); Object.freeze(rows); }\nexport const edgeSeekerTables = Object.freeze(tables);\n`;
if (check) assert(readFileSync(jsFile, "utf8") === jsContent, "Edge Seeker parity fixtures are stale");
else { mkdirSync(new URL("../tests/fixtures/", import.meta.url), { recursive: true }); writeFileSync(jsFile, jsContent); }
